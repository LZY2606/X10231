"""Offline domain case pack: “流束换算台” ADCP beam/attitude/quality ladder.

Everything is deterministic and lives inside the repository (no generic
spreadsheet). Beam velocities are generated by a forward model so that
instrument/ship/earth results are physically consistent; sources are stored as
flat, separately-typed immutable records and assembled into a pipeline view
only at derivation time.
"""
from __future__ import annotations

import math
from typing import Any, Dict, List, Optional

import numpy as np

from adcp.frames import attitude_matrix, mount_matrix
from adcp.geometry import beam_matrix
from adcp.units import quantity

N_PINGS = 12
N_CELLS = 6


def _true_profile(cell: int) -> List[float]:
    # earth-absolute water velocity [east, north, up] m/s, depth shear
    depth = 2.0 + cell
    return [0.30 + 0.02 * cell, -0.15 - 0.01 * cell,
            0.01 * math.sin(depth)]


def _ship_velocity(ping: int) -> List[float]:
    return [0.50 + 0.01 * ping, 0.05 * math.cos(ping), 0.0]


def _headings() -> List[float]:
    hs = [10.0, 10.0, 12.0, 14.0, 355.0, 2.0, 6.0, 8.0, 8.0, 9.0, 9.0, 10.0]
    return hs


def _sid(counter: List[int]) -> str:
    counter[0] += 1
    return f"s{counter[0]:04d}"


def build_case_pack() -> Dict[str, Any]:
    counter = [0]
    headings = _headings()
    pitch = [0.5 * math.sin(i / 3.0) for i in range(N_PINGS)]
    roll = [0.3 * math.cos(i / 4.0) for i in range(N_PINGS)]
    geom = {"version": "geom-A", "beam_angle_deg": 20.0,
            "azimuths_deg": [45.0, 135.0, 225.0, 315.0], "facing": "down"}
    mount = {"version": "mount-A", "pitch_deg": 0.0, "roll_deg": 0.0,
             "heading_deg": 0.0}
    decl = {"version": "decl-A", "deg": 7.0}

    B = beam_matrix(geom)
    mm = mount_matrix(mount)
    sources: List[dict] = []

    def add(stype: str, value: Any, unit: str, ping: Optional[int] = None,
            cell: Optional[int] = None, beam: Optional[int] = None,
            time_index: Optional[int] = None, note: str = "") -> str:
        sid = _sid(counter)
        sources.append({"sid": sid, "type": stype, "ping": ping, "cell": cell,
                        "beam": beam, "time_index": time_index,
                        "value": value, "unit": unit, "rev": 1, "note": note})
        return sid

    for i in range(N_PINGS):
        add("ping_time", float(i), "s", ping=i, note="ensemble time")

    # attitude series (sample time index == ping time here); t=7 removed -> gap
    for i, h in enumerate(headings):
        if i == 7:
            continue
        add("heading", h, "deg", time_index=i,
            note="seam 355->2 between pings 4,5" if i in (4, 5) else "")
        add("pitch", round(pitch[i], 4), "deg", time_index=i)
        add("roll", round(roll[i], 4), "deg", time_index=i)

    # bin depths; cell 5 is recorded in an unconvertible representation
    for c in range(N_CELLS):
        if c == 5:
            add("bin_depth", "NA", "m", cell=c,
                note="blanked / unreadable depth, kept with diagnostic")
        else:
            add("bin_depth", round(2.0 + c, 3), "m", cell=c)

    for pno in range(N_PINGS):
        h = headings[pno]
        att = attitude_matrix(h, pitch[pno], roll[pno], decl["deg"])
        ship_e = np.asarray(_ship_velocity(pno))
        # bottom track: velocity of ship over ground expressed on beams
        vs = np.linalg.solve(att, ship_e)
        vi_bt = np.linalg.solve(mm, vs)
        vb_bt = B @ vi_bt
        for k in range(4):
            add("bt_beam_velocity", round(float(vb_bt[k]), 4), "m/s",
                ping=pno, beam=k)
            add("bt_correlation", 200, "count", ping=pno, beam=k)
            add("bt_amplitude", 120, "count", ping=pno, beam=k)
            add("bt_bad_flag", False, "flag", ping=pno, beam=k)

        for cno in range(N_CELLS):
            true_w = np.asarray(_true_profile(cno))
            w_earth = true_w + ship_e  # water relative to moving ship
            vs = np.linalg.solve(att, w_earth)
            vi = np.linalg.solve(mm, vs)
            vb = B @ vi
            for k in range(4):
                val = round(float(vb[k]), 4)
                unit = "m/s"
                note = ""
                if pno == 11 and cno == 0 and k == 0:
                    val = round(float(vb[k]) * 100.0, 3)
                    unit = "cm/s"  # raw representation preserved
                    note = "recorded in cm/s"
                if pno == 9:
                    val = round(val + (0.45 if k == 0 else 0.0), 4)
                add("beam_velocity", val, unit, ping=pno, cell=cno, beam=k,
                    note=note)
                corr = 190
                amp = 115
                flag = False
                note_q = ""
                if pno == 2 and k == 1:
                    flag = True
                    corr = 40
                    note_q = "single beam failure"
                add("correlation", corr, "count", ping=pno, cell=cno, beam=k,
                    note=note_q)
                add("amplitude", amp, "count", ping=pno, cell=cno, beam=k)
                add("bad_flag", flag, "flag", ping=pno, cell=cno, beam=k)

    return {
        "dataset_id": "liushu-conversion-bench-v1",
        "title": "流束换算台：ADCP 波束速度、姿态旋转与质量层级",
        "parameters": {"geometry": geom, "mount": mount,
                       "declination": decl,
                       "thresholds": {"min_correlation": 64.0,
                                      "min_amplitude": 30.0},
                       "transform_order": "mount_first",
                       "attitude_max_gap": 0.75,
                       "error_velocity_limit": 0.15},
        "meta": {"n_pings": N_PINGS, "n_cells": N_CELLS,
                 "removed_attitude_sample": 7},
        "sources": sources,
    }


# --------------------------------------------------------------------------- #
# Flat immutable sources -> nested view consumed by adcp.pipeline
# --------------------------------------------------------------------------- #

def _rec(src: dict) -> dict:
    unit = src["unit"]
    if unit in ("count", "flag"):
        if unit == "flag":
            return {"value": src["value"], "unit": "flag", "kind": "flag",
                    "canonical": 1 if src["value"] else 0, "diagnostic": None,
                    "ok": True, "ref": src["sid"], "rev": src["rev"]}
        q = quantity(src["value"], "count")
        d = q.to_dict()
        d["canonical"] = d.pop("canonical_value")
        d.update({"ref": src["sid"], "rev": src["rev"], "ok": q.ok})
        return d
    allowed = "velocity" if src["type"] in (
        "beam_velocity", "bt_beam_velocity") else (
        "length" if src["type"] == "bin_depth" else "angle")
    q = quantity(src["value"], unit, allowed)
    d = q.to_dict()
    d["canonical"] = d.pop("canonical_value")
    d.update({"ref": src["sid"], "rev": src["rev"], "ok": q.ok})
    return d


def build_view(pack: Dict[str, Any],
               decisions: Optional[List[dict]] = None) -> Dict[str, Any]:
    """Assemble the active dataset view from flat source revisions."""
    params = pack["parameters"]
    n_pings = pack["meta"]["n_pings"]
    n_cells = pack["meta"]["n_cells"]

    def latest(stype, **kw):
        out = [s for s in pack["sources"] if s["type"] == stype
               and all(s.get(k) == v for k, v in kw.items())]
        return max(out, key=lambda s: s["rev"]) if out else None

    att_times, att_h, att_p, att_r = [], [], [], []
    for i in range(n_pings):
        h = latest("heading", time_index=i)
        if h is None:
            continue
        att_times.append(float(i))
        att_h.append(_rec(h))
        att_p.append(_rec(latest("pitch", time_index=i)))
        att_r.append(_rec(latest("roll", time_index=i)))

    depth_cells = []
    for c in range(n_cells):
        depth_cells.append({"cell": c, "bin_depth": _rec(
            latest("bin_depth", cell=c))})

    pings = []
    for pno in range(n_pings):
        bt = {"beam_velocity": [], "correlation": [], "amplitude": [],
              "bad_flags": []}
        for k in range(4):
            bt["beam_velocity"].append(_rec(
                latest("bt_beam_velocity", ping=pno, beam=k)))
            bt["correlation"].append(_rec(
                latest("bt_correlation", ping=pno, beam=k)))
            bt["amplitude"].append(_rec(
                latest("bt_amplitude", ping=pno, beam=k)))
            bt["bad_flags"].append(
                bool(latest("bt_bad_flag", ping=pno, beam=k)["value"]))
        cells = []
        for cno in range(n_cells):
            cell = {"cell": cno, "beam_velocity": [], "correlation": [],
                    "amplitude": [], "bad_flags": []}
            for k in range(4):
                cell["beam_velocity"].append(_rec(
                    latest("beam_velocity", ping=pno, cell=cno, beam=k)))
                cell["correlation"].append(_rec(
                    latest("correlation", ping=pno, cell=cno, beam=k)))
                cell["amplitude"].append(_rec(
                    latest("amplitude", ping=pno, cell=cno, beam=k)))
                cell["bad_flags"].append(bool(
                    latest("bad_flag", ping=pno, cell=cno, beam=k)["value"]))
            cells.append(cell)
        pings.append({"ping": pno,
                      "time": latest("ping_time", ping=pno)["value"],
                      "cells": cells, "bottom_track": bt})

    view = {
        "dataset_id": pack["dataset_id"],
        "geometry": params["geometry"], "mount": params["mount"],
        "declination": params["declination"],
        "thresholds": params["thresholds"],
        "transform_order": params.get("transform_order", "mount_first"),
        "attitude": {"times": att_times, "heading": att_h, "pitch": att_p,
                     "roll": att_r, "version": "att-1",
                     "max_gap": params.get("attitude_max_gap", 0.75)},
        "depth_cells": depth_cells, "pings": pings,
        "error_velocity_limit": params.get("error_velocity_limit", 0.15),
        "decisions": decisions or [],
    }
    return view
